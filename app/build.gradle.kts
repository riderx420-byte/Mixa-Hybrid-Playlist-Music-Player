abstract class ExportLatestApkTask : org.gradle.api.DefaultTask() {
  @get:org.gradle.api.tasks.InputFile
  abstract val apkSource: org.gradle.api.file.RegularFileProperty

  @get:org.gradle.api.tasks.OutputDirectory
  abstract val latestDir: org.gradle.api.file.DirectoryProperty

  @get:org.gradle.api.tasks.Input
  abstract val appVersionName: org.gradle.api.provider.Property<String>

  @org.gradle.api.tasks.TaskAction
  fun export() {
    val src = apkSource.get().asFile
    val outDir = latestDir.get().asFile.apply { mkdirs() }
    val baseName = "mixa-v${appVersionName.get()}"
    var target = outDir.resolve("${baseName}.apk")
    if (target.exists()) {
      var buildNum = 2
      while (outDir.resolve("${baseName}-build${buildNum}.apk").exists()) {
        buildNum++
      }
      target = outDir.resolve("${baseName}-build${buildNum}.apk")
    }
    src.copyTo(target, overwrite = false)
    logger.lifecycle("Exported APK to: latest/${target.name}")
  }
}

val exportedVersionName = android.defaultConfig.versionName ?: "1.0"

tasks.register<ExportLatestApkTask>("exportLatestApk") {
  dependsOn("assembleDebug")
  apkSource.set(layout.buildDirectory.file("outputs/apk/debug/app-debug.apk"))
  latestDir.set(rootProject.layout.projectDirectory.dir("latest"))
  appVersionName.set(exportedVersionName)
}


